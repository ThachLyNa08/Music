function parseArgs(argv) {
  const args = {
    input: DEFAULT_INPUT,
    limit: null,
    dryRun: false,
    force: false,
    market: null,
    retryFailed: false,
  };

  for (const arg of argv) {
    if (arg === '--dry-run') args.dryRun = true;
    else if (arg === '--force') args.force = true;
    else if (arg === '--retry-failed') args.retryFailed = true;
    else if (arg.startsWith('--input=')) args.input = path.resolve(PROJECT_ROOT, arg.slice('--input='.length));
    else if (arg.startsWith('--limit=')) args.limit = Math.max(Number(arg.slice('--limit='.length)) || 0, 0);
    else if (arg.startsWith('--market=')) args.market = arg.slice('--market='.length).trim().toUpperCase();
  }

  if (args.market && !['VPOP', 'KPOP', 'USUK'].includes(args.market)) {
    throw new Error('--market must be one of VPOP, KPOP, USUK');
  }

  return args;
}

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing backend .env file: ${filePath}`);
  }

  const env = {};
  for (const rawLine of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const normalizedLine = line.startsWith('export ') ? line.slice(7).trim() : line;
    const equalsIndex = normalizedLine.indexOf('=');
    if (equalsIndex === -1) continue;

    const key = normalizedLine.slice(0, equalsIndex).trim();
    let value = normalizedLine.slice(equalsIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    env[key] = value;
  }

  return env;
}

function quoteId(identifier) {
  if (!/^[A-Za-z0-9_]+$/.test(identifier)) {
    throw new Error(`Unsafe SQL identifier: ${identifier}`);
  }
  return `\`${identifier}\``;
}

