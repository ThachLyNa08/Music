async function updateArtistBio(connection, artistId, bioResult, options) {
  const selected = bioResult.selected;
  const lastfmUrl = clean(bioResult.lastfm?.lastfmUrl || (selected.source === 'lastfm' ? selected.sourceUrl : ''));
  const wikidataId = clean(selected.wikidataId || bioResult.wikidataId);

  const setClauses = [
    'bio = ?',
    'bio_source = ?',
    'bio_source_url = ?',
    'bio_fetched_at = NOW()',
  ];
  const params = [
    selected.bio,
    selected.source,
    selected.sourceUrl,
  ];

  if (lastfmUrl) {
    setClauses.push('lastfm_url = ?');
    params.push(lastfmUrl);
  }

  if (wikidataId) {
    setClauses.push('wikidata_id = ?');
    params.push(wikidataId);
  }

  params.push(artistId);

  const existingBioGuard = options.force ? '' : ' AND (bio IS NULL OR TRIM(bio) = "")';
  const [result] = await connection.query(
    `UPDATE artists SET ${setClauses.join(', ')} WHERE id = ?${existingBioGuard}`,
    params
  );

  return result.affectedRows > 0;
}

function resultRow(row, status, details = {}) {
  return {
    artist_id: row.artist_id,
    artist_name: row.artist_name,
    market: row.market,
    status,
    bio_source: clean(details.bio_source),
    bio_source_url: clean(details.bio_source_url),
    wikidata_id: clean(details.wikidata_id),
    lastfm_url: clean(details.lastfm_url),
    bio_length: details.bio_length || 0,
    error_message: clean(details.error_message),
  };
}

function loadRetryIds() {
  if (!fs.existsSync(RESULT_PATH)) return new Set();

  const previousRows = parseCsv(fs.readFileSync(RESULT_PATH, 'utf8'));
  return new Set(
    previousRows
      .filter((row) => {
        const status = clean(row.status).toLowerCase();
        return status.startsWith('failed') || status.startsWith('skipped_low_confidence') || status === 'no_bio_found';
      })
      .map((row) => clean(row.artist_id))
      .filter(Boolean)
  );
}

function loadInputRows(args) {
  if (!fs.existsSync(args.input)) {
    throw new Error(`Input CSV not found: ${args.input}`);
  }

  let rows = parseCsv(fs.readFileSync(args.input, 'utf8'))
    .map((row) => ({
      ...row,
      artist_id: clean(row.artist_id),
      artist_name: clean(row.artist_name),
      market: clean(row.market).toUpperCase(),
    }))
    .filter((row) => row.artist_id && row.artist_name);

  if (args.market) {
    rows = rows.filter((row) => row.market === args.market);
  }

  if (args.retryFailed) {
    const retryIds = loadRetryIds();
    if (retryIds.size > 0) {
      rows = rows.filter((row) => retryIds.has(row.artist_id));
    } else {
      rows = rows.filter((row) => clean(row.error_message));
    }
  }

  rows.sort((left, right) => {
    const leftPending = clean(left.bio_status) === 'pending' ? 1 : 0;
    const rightPending = clean(right.bio_status) === 'pending' ? 1 : 0;
    if (rightPending !== leftPending) return rightPending - leftPending;
    return (Number(right.song_count) || 0) - (Number(left.song_count) || 0);
  });

  if (args.limit !== null) {
    rows = rows.slice(0, args.limit);
  }

  return rows;
}

async function processArtist(connection, row, env, args) {
  const label = `${row.artist_name} (#${row.artist_id}, ${row.market || 'UNKNOWN'})`;
  console.log(`Processing ${label}`);

  const dbArtist = await getDbArtist(connection, row.artist_id);
  if (!dbArtist) {
    console.log('  skipped: artist_id not found in DB');
    return resultRow(row, 'skipped_not_found', { error_message: 'artist_id not found in DB' });
  }

  if (nameSimilarity(row.artist_name, dbArtist.name) < 0.8) {
    console.log(`  skipped: DB name mismatch (${dbArtist.name})`);
    return resultRow(row, 'skipped_name_mismatch', { error_message: `DB name is ${dbArtist.name}` });
  }

  if (!args.force && clean(dbArtist.bio)) {
    console.log('  skipped: bio already exists');
    return resultRow(row, 'skipped_existing_bio', { bio_length: clean(dbArtist.bio).length });
  }

  const bioResult = await findBio(row, env);
  if (!bioResult.selected) {
    console.log('  failed: no high-confidence bio source');
    return resultRow(row, 'failed_no_bio_found', {
      wikidata_id: bioResult.wikidataId,
      lastfm_url: bioResult.lastfm?.lastfmUrl,
      error_message: 'No high-confidence Wikipedia/Last.fm bio found',
    });
  }

  const selected = bioResult.selected;
  const lastfmUrl = clean(bioResult.lastfm?.lastfmUrl || (selected.source === 'lastfm' ? selected.sourceUrl : ''));
  const wikidataId = clean(selected.wikidataId || bioResult.wikidataId);

  console.log(`  source selected: ${selected.source} (${selected.sourceUrl})`);
  console.log(`  confidence: ${bioResult.confidence?.score || bioResult.confidence || 'n/a'}`);

  if (args.dryRun) {
    console.log('  dry-run: DB update skipped');
    return resultRow(row, 'dry_run_would_update', {
      bio_source: selected.source,
      bio_source_url: selected.sourceUrl,
      wikidata_id: wikidataId,
      lastfm_url: lastfmUrl,
      bio_length: selected.bio.length,
    });
  }

  const updated = await updateArtistBio(connection, row.artist_id, bioResult, args);
  if (!updated) {
    console.log('  skipped: DB update guard prevented overwrite');
    return resultRow(row, 'skipped_existing_bio', {
      bio_source: selected.source,
      bio_source_url: selected.sourceUrl,
      wikidata_id: wikidataId,
      lastfm_url: lastfmUrl,
      bio_length: selected.bio.length,
      error_message: 'Existing bio was not overwritten',
    });
  }

  console.log('  DB updated');
  return resultRow(row, 'completed', {
    bio_source: selected.source,
    bio_source_url: selected.sourceUrl,
    wikidata_id: wikidataId,
    lastfm_url: lastfmUrl,
    bio_length: selected.bio.length,
  });
}

function summarize(results) {
  const completed = results.filter((row) => row.status === 'completed' || row.status === 'dry_run_would_update').length;
  const failed = results.filter((row) => row.status.startsWith('failed')).length;
  const skipped = results.length - completed - failed;

  console.log('');
  console.log(`Summary completed: ${completed}`);
  console.log(`Summary failed: ${failed}`);
  console.log(`Summary skipped: ${skipped}`);
  console.log(`Result CSV: ${RESULT_PATH}`);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const env = parseEnvFile(BACKEND_ENV_PATH);
  const rows = loadInputRows(args);

  const connection = await mysql.createConnection({
    host: env.DB_HOST || 'localhost',
    port: Number(env.DB_PORT || 3306),
    database: env.DB_NAME || 'musicflow',
    user: env.DB_USER || 'root',
    password: env.DB_PASSWORD || '',
    charset: 'utf8mb4',
  });

  try {
    await ensureArtistSchema(connection);

    console.log(`Input CSV: ${args.input}`);
    console.log(`Artists selected: ${rows.length}`);
    console.log(`Dry run: ${args.dryRun ? 'yes' : 'no'}`);
    console.log(`Force overwrite: ${args.force ? 'yes' : 'no'}`);
    if (!clean(env.LASTFM_API_KEY)) {
      console.log('Last.fm: skipped because LASTFM_API_KEY is empty');
    }
    console.log('');

    const results = [];

    for (const row of rows) {
      try {
        const result = await processArtist(connection, row, env, args);
        results.push(result);
      } catch (error) {
        console.log(`  failed: ${error.message}`);
        results.push(resultRow(row, 'failed_error', { error_message: error.message }));
      }

      await sleep(RATE_LIMIT_MS);
    }

    writeResultCsv(results);
    summarize(results);
  } finally {
    await connection.end();
  }
}

main().catch((error) => {
  console.error(`Crawl artist bios failed: ${error.message}`);
  process.exit(1);
});
