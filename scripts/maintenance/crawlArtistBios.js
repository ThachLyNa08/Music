function createMissingColumnsMigration(missingColumns) {
  fs.mkdirSync(path.dirname(MIGRATION_PATH), { recursive: true });

  const lines = [
    '-- Adds artist bio crawler columns when they are missing.',
    '-- Generated by scripts/maintenance/crawlArtistBios.js.',
    '',
    'ALTER TABLE artists',
    missingColumns
      .map(([column, definition], index) => {
        const suffix = index === missingColumns.length - 1 ? ';' : ',';
        return `  ADD COLUMN IF NOT EXISTS ${quoteId(column)} ${definition}${suffix}`;
      })
      .join('\n'),
    '',
  ];

  fs.writeFileSync(MIGRATION_PATH, lines.join('\n'), 'utf8');
}

